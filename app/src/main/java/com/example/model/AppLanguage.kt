enum class AppLanguage(val code: String, val displayName: String, val flag: String) {
    BE("be", "Беларуская", "🇧🇾"),
    UK("uk", "Українська", "🇺🇦"),
    RU("ru", "Русский", "⚪"),
    EN("en", "English", "🇬🇧"),
    DE("de", "Deutsch", "🇩🇪"),
    ES("es", "Español", "🇪🇸");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) } ?: BE
    }
}


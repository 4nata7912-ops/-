    BE("be", "Беларуская", "BY"),
    UK("uk", "Українська", "UA"),
    RU("ru", "Русский", "RU"),
    EN("en", "English", "EN"),
    DE("de", "Deutsch", "DE"),
    ES("es", "Español", "ES");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) } ?: BE
    }
}

